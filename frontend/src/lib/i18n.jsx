function getInitialLanguage() {
  const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return SUPPORTED_LANGUAGES.has(stored) ? stored : "vi";
}

function interpolate(template, values = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key) => values[key] ?? "");
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage);

  const value = useMemo(
    () => ({
      language,
      setLanguage(nextLanguage) {
        const safeLanguage = SUPPORTED_LANGUAGES.has(nextLanguage) ? nextLanguage : "vi";
        window.localStorage.setItem(LANGUAGE_STORAGE_KEY, safeLanguage);
        setLanguageState(safeLanguage);
      },
      t(key, values) {
        const manager = language === "vi" ? managerVietnamese : managerEnglish;
        const template = translations[language][key] || manager[key] || translations.en[key] || key;
        return interpolate(template, values);
      },
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }

  return context;
}
